-- Proctored-exam schema for the production PostgreSQL database.
--
-- Production runs with spring.jpa.hibernate.ddl-auto=validate, so nothing here is created by
-- Hibernate. Spring executes this file before the entity manager is built (spring.sql.init runs
-- first unless spring.jpa.defer-datasource-initialization is set), which is what lets validate
-- pass against a database that was written before these columns existed.
--
-- Every statement is idempotent: a fresh database gets the full shape, an already-migrated one
-- is unchanged, and running it twice is safe.

-- The attempt row became the exam session itself: a server-owned clock, the exact questions served,
-- the per-sitting letter order and the answer sheet as it was saved.
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS status VARCHAR(255) NOT NULL DEFAULT 'IN_PROGRESS';
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS draw_token_id VARCHAR(64);
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS attempt_number INTEGER;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS started_at TIMESTAMP;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS deadline TIMESTAMP;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS submitted_at TIMESTAMP;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS total_questions INTEGER;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS correct_count INTEGER;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS question_ids TEXT;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS option_orders TEXT;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS answers TEXT;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS violation_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS violation_points INTEGER NOT NULL DEFAULT 0;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS integrity VARCHAR(255) NOT NULL DEFAULT 'CLEAN';
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS review_note TEXT;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS reviewed_by BIGINT;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMP;
ALTER TABLE exam_attempt ADD COLUMN IF NOT EXISTS user_agent VARCHAR(512);

-- Rows written before this change could only have been created by handing an exam in, so they are
-- submitted and clean. Leaving them any other way would revoke credentials from learners who
-- already passed and hide their results from the register. attempt_number is deliberately not set
-- here: the block below counts the sittings a learner actually has.
UPDATE exam_attempt
SET status = 'SUBMITTED',
    integrity = 'CLEAN',
    started_at = COALESCE(started_at, attempted_at),
    submitted_at = COALESCE(submitted_at, attempted_at),
    deadline = COALESCE(deadline, attempted_at + INTERVAL '40 minutes')
WHERE question_ids IS NULL;

-- Number the sittings a learner already has, oldest first, so the attempt cap sees a real history
-- rather than a column of the same number. Only rows that never had one, so a later re-run cannot
-- rewrite a number the register has already been read with.
WITH ranked AS (
    SELECT id, ROW_NUMBER() OVER (PARTITION BY user_id, course_id ORDER BY attempted_at, id) AS seat
    FROM exam_attempt
    WHERE attempt_number IS NULL
)
UPDATE exam_attempt a
SET attempt_number = r.seat
FROM ranked r
WHERE a.id = r.id;

CREATE INDEX IF NOT EXISTS idx_exam_attempt_open_sittings
    ON exam_attempt (user_id, course_id, status);

-- The sweep that closes abandoned sittings reads this every minute.
CREATE INDEX IF NOT EXISTS idx_exam_attempt_sweep
    ON exam_attempt (status, deadline);

-- The integrity queue is ordered by weight, worst first.
CREATE INDEX IF NOT EXISTS idx_exam_attempt_integrity
    ON exam_attempt (integrity, violation_points DESC, attempted_at DESC);

-- What the browser noticed, stamped by the server rather than by the candidate's clock.
CREATE TABLE IF NOT EXISTS exam_proctor_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES exam_attempt (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    kind VARCHAR(32) NOT NULL,
    severity VARCHAR(10) NOT NULL DEFAULT 'LOW',
    detail VARCHAR(500),
    client_reported_at TIMESTAMP,
    server_received_at TIMESTAMP NOT NULL,
    elapsed_seconds BIGINT
);

CREATE INDEX IF NOT EXISTS idx_exam_proctor_event_attempt
    ON exam_proctor_event (attempt_id, server_received_at);
CREATE INDEX IF NOT EXISTS idx_exam_proctor_event_user
    ON exam_proctor_event (user_id);

-- Consented camera frames, kept separate so the timeline stays cheap to read.
CREATE TABLE IF NOT EXISTS exam_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES exam_attempt (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    label VARCHAR(32) NOT NULL,
    server_received_at TIMESTAMP NOT NULL,
    image_data_url TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_exam_snapshot_attempt
    ON exam_snapshot (attempt_id, server_received_at);

-- A credential now traces to the specific attempt that earned it.
ALTER TABLE certificate ADD COLUMN IF NOT EXISTS attempt_id BIGINT;
